import { NextRequest, NextResponse } from 'next/server';
import { query } from '@repo/database';
import type { BuildDetail } from '@repo/shared';
import { authErrorResponse, requestContext } from '@/lib/auth/context';
import { briefInWorkspace, isUuid } from '@/lib/briefs/store';
import { getBuild } from '@/lib/builds/store';
import { checkDeliverRequest } from '@/lib/builds/policy';
import { DeliveryError, openPullRequest } from '@/lib/builds/github';
import { checkRateLimit } from '@/lib/security/rate_limit';

export const dynamic = 'force-dynamic';

const notFound = () => NextResponse.json({ error: 'Build not found.' }, { status: 404 });

/**
 * Delivers a finished build as a new branch and a draft pull request, only on a maintainer's explicit
 * approval in this request: { repo: 'owner/name', branch, approve: true }. Without GITHUB_BUILD_TOKEN
 * nothing is pushed; the downloadable diff is the delivery.
 */
export async function POST(req: NextRequest, { params }: { params: { id: string; buildId: string } }) {
  const rateLimit = checkRateLimit(req, 'deliver_build', { maxRequests: 5, windowMs: 60 * 1000 });
  if (!rateLimit.allowed && rateLimit.response) return rateLimit.response;
  if (!isUuid(params.id) || !isUuid(params.buildId)) return notFound();
  const body = await req.json().catch(() => null);
  try {
    const ctx = await requestContext();
    if (!(await briefInWorkspace(params.id, ctx.workspaceId))) return notFound();
    const build = await getBuild(params.id, params.buildId, ctx.workspaceId);
    if (!build) return notFound();
    const decision = checkDeliverRequest({
      role: ctx.role,
      body,
      buildStatus: build.status,
      hasChangeSet: build.files.length > 0
    });
    if (!decision.ok) return NextResponse.json({ error: decision.error }, { status: decision.status });

    const token = process.env.GITHUB_BUILD_TOKEN;
    const diffUrl = `/api/briefs/${params.id}/build/${params.buildId}?format=diff`;
    if (!token) {
      return NextResponse.json(
        { error: 'Pull-request delivery is not configured (GITHUB_BUILD_TOKEN is not set). Download the diff and apply it yourself.', delivery: 'diff', diffUrl },
        { status: 409 }
      );
    }

    // One delivery at a time per build: claim it before touching GitHub
    const claimed = await query(
      `UPDATE builds SET delivery_json = jsonb_build_object('state', 'delivering', 'repo', $2::text, 'branch', $3::text), updated_at = NOW()
       WHERE id = $1 AND status IN ('succeeded', 'awaiting_approval') AND (delivery_json IS NULL OR delivery_json->>'state' = 'failed')
       RETURNING id`,
      [build.id, decision.value.repo, decision.value.branch]
    );
    if (!claimed.rowCount) return NextResponse.json({ error: 'This build is already being delivered.' }, { status: 409 });

    try {
      const pr = await openPullRequest({
        token,
        repo: decision.value.repo,
        branch: decision.value.branch,
        files: build.fileContents,
        pathPrefix: build.report?.pathPrefix || `open-eye/build-${build.id.slice(0, 8)}`,
        title: `Open Eye build ${build.id.slice(0, 8)}: ${[...build.scope.roadmapTaskIds, ...build.scope.requirements].join(', ').slice(0, 120)}`,
        body: pullRequestBody(build)
      });
      const delivery = {
        repo: decision.value.repo,
        branch: decision.value.branch,
        baseBranch: pr.baseBranch,
        pullRequestUrl: pr.pullRequestUrl,
        pullRequestNumber: pr.pullRequestNumber,
        approvedBy: ctx.userId,
        deliveredAt: new Date().toISOString()
      };
      await query(`UPDATE builds SET status = 'delivered', delivery_json = $2, updated_at = NOW() WHERE id = $1`, [build.id, JSON.stringify(delivery)]);
      return NextResponse.json({ delivered: true, ...delivery });
    } catch (error: any) {
      const message = error instanceof DeliveryError ? error.message : 'GitHub could not be reached.';
      await query(
        `UPDATE builds SET delivery_json = jsonb_build_object('state', 'failed', 'error', $2::text), updated_at = NOW() WHERE id = $1`,
        [build.id, message]
      );
      return NextResponse.json({ error: message, delivery: 'diff', diffUrl }, { status: error instanceof DeliveryError ? error.status : 502 });
    }
  } catch (error: any) {
    const denied = authErrorResponse(error);
    if (denied) return denied;
    console.error('Error delivering build:', error?.message);
    return NextResponse.json({ error: 'Could not deliver the build.' }, { status: 500 });
  }
}

function pullRequestBody(build: BuildDetail): string {
  const r = build.report;
  const list = (title: string, items?: string[]) => (items && items.length ? `\n### ${title}\n${items.map((i) => `- ${i}`).join('\n')}\n` : '');
  const t = r?.totals;
  return [
    `Generated by Open Eye build \`${build.id}\` in an isolated sandbox and opened after a maintainer's explicit approval.`,
    '',
    `**Tests:** ${r?.outcome ?? 'unknown'}${t ? ` (${t.passed} passed, ${t.failed} failed, ${t.error} errors, ${t.skipped} skipped)` : ''} after ${r?.iterations ?? build.iterations} iteration(s).`,
    r?.testCommand ? `**Test command:** \`${r.testCommand}\` (${r.network || 'network unknown'})` : '',
    list('Passed', r?.passed),
    list('Failed', r?.failed),
    list('Untested', r?.untested),
    list('Needs a human', r?.needsHuman)
  ]
    .filter(Boolean)
    .join('\n');
}
